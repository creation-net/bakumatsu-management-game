export function getDiagnosisManagementTheme(
  primaryId: DiagnosisCharacterId,
  secondaryId: DiagnosisCharacterId,
): DiagnosisManagementTheme {
  const source = managementThemeSources[`${primaryId}-${secondaryId}`];
  const primary = diagnosisCharacters.find((character) => character.id === primaryId);
  const secondary = diagnosisCharacters.find((character) => character.id === secondaryId);

  if (!source || !primary || !secondary) {
    return {
      theme: "人と組織の強みを生かし、経営課題を前へ進める取り組みです。",
      reason: "二つの資質を状況に応じて使い分けられるためです。",
      action: "目指す成果と役割を明確にし、小さな実践から始めてください。",
    };
  }

  return {
    ...source,
    reason: `${primary.type}の「${primary.combinationAction}」と、${secondary.type}の「${secondary.combinationAction}」が組み合わさるためです。`,
  };
}

